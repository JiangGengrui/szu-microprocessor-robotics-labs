#ifndef __FACE_APP_H
#define __FACE_APP_H
#include "main.h"
#include "ui.h"

/* =========================================================================
 * 应用状态机(face-id 阶段七~九的总装)
 *
 *   页面:  首页(静态文字)  <--K0-->  工作页(摄像头实时预览 + 状态机)
 *
 *   工作页按键(键位沿用 exp3 / 官方例程):
 *     KEY1 : 模式循环  预览 -> 录入 -> 识别 -> 标定 -> 回放 -> 预览
 *     KEY2 : 录入/回放模式换人(1~5);  识别/标定模式换算法(MSE->LBP->COL->PCA)
 *     KEY0 : 录入模式拍照并存图; 识别/标定模式拍照并识别/测分数; 回放模式翻下一张
 *     WK_UP: 长按 -> 预览模式回首页; 录入/识别/标定模式清空图库;
 *            回放模式回预览(回放里不清库, 避免看图中误擦)
 * ========================================================================= */

/**
 * @brief 初始化(在 LCD + 摄像头初始化之后调用)
 * @param cam_ok 摄像头初始化结果(1=正常)
 */
void face_app_init(uint8_t cam_ok);

/** 进入工作页: 模式复位为"预览"并打开实时取景框 */
void face_app_enter(void);

/** 离开工作页: 关闭实时取景框 */
void face_app_leave(void);

/**
 * @brief 主循环轮询: 处理按键 + 状态机
 * @retval 1 = 请求返回首页(调用方需 camera_stop + 重画首页)
 */
uint8_t face_app_poll(void);

/** NOR Flash 是否可用(0=仅内存降级模式) */
uint8_t face_app_flash_ok(void);

#endif
